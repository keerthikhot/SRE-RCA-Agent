import os
import html
from datetime import datetime, timezone
from jinja2 import Environment, FileSystemLoader, select_autoescape

TEMPLATE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates")
env = Environment(loader=FileSystemLoader(TEMPLATE_DIR), autoescape=select_autoescape(["html", "j2"]))
REPORT_DIR = os.getenv("REPORT_DIR", "/tmp/reports")

# Store reference to latest report for easy web viewing
LATEST_REPORT: dict = {}

def render_rca(rca: dict) -> tuple[str, str]:
    global LATEST_REPORT
    now = datetime.now(timezone.utc)
    timestamp_str = now.strftime("%Y-%m-%d %H:%M UTC")
    page = env.get_template("rca.html.j2").render(r=rca, generated=timestamp_str)
    
    os.makedirs(REPORT_DIR, exist_ok=True)
    name = f"rca-{now.strftime('%Y%m%d-%H%M%S')}.html"
    filepath = os.path.join(REPORT_DIR, name)
    
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(page)
    
    LATEST_REPORT = {
        "filename": name,
        "filepath": filepath,
        "content": page,
        "timestamp": timestamp_str,
        "rca": rca
    }
    
    return name, page

